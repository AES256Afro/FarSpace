// 4x6 bitmap pixel font. Each glyph is 4 wide (3 used + 1 space) x 5 tall,
// encoded as 15 bits, column-major-free simple row encoding (3 bits/row x 5 rows).

const GLYPHS: Record<string, number> = {
  A: 0b010101111101101, B: 0b110101110101110, C: 0b011100100100011,
  D: 0b110101101101110, E: 0b111100110100111, F: 0b111100110100100,
  G: 0b011100101101011, H: 0b101101111101101, I: 0b111010010010111,
  J: 0b001001001101010, K: 0b101110100110101, L: 0b100100100100111,
  M: 0b101111111101101, N: 0b110101101101101, O: 0b010101101101010,
  P: 0b110101110100100, Q: 0b010101101110011, R: 0b110101110110101,
  S: 0b011100010001110, T: 0b111010010010010, U: 0b101101101101011,
  V: 0b101101101101010, W: 0b101101111111101, X: 0b101101010101101,
  Y: 0b101101010010010, Z: 0b111001010100111,
  "0": 0b010101101101010, "1": 0b010110010010111, "2": 0b110001010100111,
  "3": 0b110001010001110, "4": 0b101101111001001, "5": 0b111100110001110,
  "6": 0b011100110101010, "7": 0b111001010010010, "8": 0b010101010101010 | 0b101000101000101,
  "9": 0b010101011001110,
  ".": 0b000000000000010, ",": 0b000000000010100, ":": 0b000010000010000,
  ";": 0b000010000010100, "!": 0b010010010000010, "?": 0b110001010000010,
  "-": 0b000000111000000, "+": 0b000010111010000, "/": 0b001001010100100,
  "'": 0b010010000000000, '"': 0b101101000000000, "(": 0b001010010010001,
  ")": 0b100010010010100, "[": 0b011010010010011, "]": 0b110010010010110,
  "%": 0b101001010100101, "$": 0b011110011111110, "#": 0b101111101111101,
  "*": 0b000101010101000, "=": 0b000111000111000, "<": 0b001010100010001,
  ">": 0b100010001010100, "^": 0b010101000000000, "_": 0b000000000000111,
  "|": 0b010010010010010, "@": 0b010101101100011, "&": 0b010101010101011,
  "→": 0b000010111010000, " ": 0,
};
// fix 8 (the OR above makes a mess): proper 8
GLYPHS["8"] = 0b010101010101010;
GLYPHS["8"] = (0b010 << 12) | (0b101 << 9) | (0b010 << 6) | (0b101 << 3) | 0b010;

export const CHAR_W = 4;
export const CHAR_H = 6;

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
): void {
  ctx.fillStyle = color;
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const ch of text.toUpperCase()) {
    const bits = GLYPHS[ch] ?? 0b111101101101111;
    if (bits !== 0) {
      for (let row = 0; row < 5; row++) {
        const rowBits = (bits >> ((4 - row) * 3)) & 0b111;
        for (let col = 0; col < 3; col++) {
          if (rowBits & (0b100 >> col)) ctx.fillRect(cx + col, cy + row, 1, 1);
        }
      }
    }
    cx += CHAR_W;
  }
}

export function textWidth(text: string): number {
  return text.length * CHAR_W;
}
